'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { ansi16 } = require('../ansi');

const DIR = path.join(os.homedir(), '.config', 'alacritty');

module.exports = {
  id: 'alacritty',
  label: 'Alacritty',
  detect: () => fs.existsSync('/Applications/Alacritty.app') || fs.existsSync(DIR),
  build(p) {
    const c = p.colors;
    const a = ansi16(p);
    const toml = `# ${p.name} -- generated by Hues
[colors.primary]
background = "${c.bg}"
foreground = "${c.fg}"
bright_foreground = "${a.brightWhite}"

[colors.cursor]
text = "${c.bg}"
cursor = "${c.fg}"

[colors.selection]
text = "${c.fg}"
background = "${c.selection}"

[colors.normal]
black = "${a.black}"
red = "${a.red}"
green = "${a.green}"
yellow = "${a.yellow}"
blue = "${a.blue}"
magenta = "${a.magenta}"
cyan = "${a.cyan}"
white = "${a.white}"

[colors.bright]
black = "${a.brightBlack}"
red = "${a.brightRed}"
green = "${a.brightGreen}"
yellow = "${a.brightYellow}"
blue = "${a.brightBlue}"
magenta = "${a.brightMagenta}"
cyan = "${a.brightCyan}"
white = "${a.brightWhite}"
`;
    return [{ name: `${p.slug}.toml`, content: toml }];
  },
  install(p, files, { write }) {
    fs.mkdirSync(path.join(DIR, 'themes'), { recursive: true });
    write(files[0], path.join(DIR, 'themes', files[0].name));
    return { notes: [`installed ~/.config/alacritty/themes/${files[0].name}`, `add to alacritty.toml: general.import = ["~/.config/alacritty/themes/${files[0].name}"]`] };
  },
};
