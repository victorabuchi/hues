'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { rgbArray, blend, lighten, darken } = require('../color');

/**
 * A real Chromium browser theme. Dracula ships no browser theme for
 * Chrome/Brave (only a DevTools one), so this fills that gap.
 * Colors-only themes are valid under MV3 and need no image assets.
 */
module.exports = {
  id: 'chromium',
  label: 'Brave / Chrome (browser theme)',
  detect: () =>
    fs.existsSync('/Applications/Brave Browser.app') ||
    fs.existsSync('/Applications/Google Chrome.app') ||
    fs.existsSync('/Applications/Google Chrome Canary.app') ||
    fs.existsSync('/Applications/Chromium.app'),

  build(p) {
    const c = p.colors;
    const dark = p.appearance !== 'light';
    const inactiveFrame = dark ? darken(c.bgDarker, 0.25) : lighten(c.bgDark, 0.3);

    const manifest = {
      manifest_version: 3,
      name: `${p.name} (Hues)`,
      version: '1.0.0',
      description: `${p.name} browser theme, generated by Hues.`,
      theme: {
        colors: {
          frame: rgbArray(c.bgDarker),
          frame_inactive: rgbArray(inactiveFrame),
          frame_incognito: rgbArray(darken(c.bgDarker, 0.3)),
          toolbar: rgbArray(c.bg),
          tab_text: rgbArray(c.fg),
          tab_background_text: rgbArray(c.comment),
          bookmark_text: rgbArray(c.fg),
          toolbar_text: rgbArray(c.fg),
          omnibox_background: rgbArray(c.bgLight),
          omnibox_text: rgbArray(c.fg),
          ntp_background: rgbArray(c.bg),
          ntp_text: rgbArray(c.fg),
          ntp_link: rgbArray(c.cyan),
          button_background: rgbArray(c.bgLight),
        },
        tints: {
          // -1 means "leave alone"; buttons get tinted toward the accent hue.
          buttons: [-1, -1, dark ? 0.96 : 0.2],
        },
        properties: {
          ntp_logo_alternate: dark ? 1 : 0,
        },
      },
    };

    return [{ name: 'manifest.json', content: JSON.stringify(manifest, null, 2) + '\n' }];
  },

  /**
   * Chromium cannot install an unpacked theme from the CLI -- that is a
   * deliberate browser security boundary, not a gap in hues. We stage the
   * folder and tell the user the one manual step.
   */
  install(p, files, { write, outDir }) {
    files.forEach((f) => write(f));
    return {
      manual: true,
      notes: [
        `staged theme at ${outDir}`,
        'load it: brave://extensions (or chrome://extensions) -> enable Developer mode -> "Load unpacked" -> pick that folder',
      ],
    };
  },
};
