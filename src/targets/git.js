'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');

const GITCONFIG = path.join(os.homedir(), '.gitconfig');
const MARK_START = '# >>> varjo >>>';
const MARK_END = '# <<< varjo <<<';

module.exports = {
  id: 'git',
  label: 'git (diff/status colors)',
  detect: () => true,

  /**
   * git only understands 8 named colors + 256 indices, so this is a mapping
   * onto what git can express rather than the full palette.
   */
  build(p) {
    const dark = p.appearance !== 'light';
    const lines = [
      MARK_START,
      `# ${p.name} -- generated by Varjo`,
      '[color]', '\tui = auto',
      '[color "branch"]', '\tcurrent = cyan bold reverse', '\tlocal = white', '\tremote = cyan',
      '[color "diff"]', '\tmeta = white', '\tfrag = cyan bold reverse', '\tfunc = cyan',
      '\told = red', '\tnew = green', '\twhitespace = magenta reverse',
      '[color "status"]', '\tadded = green', '\tchanged = yellow', '\tuntracked = red',
      '\tupdated = green bold', '\tremoteBranch = cyan bold', '\tunmerged = magenta bold reverse',
      '[color "grep"]', `\tlinenumber = ${dark ? 'white' : 'black'}`, '\tmatch = yellow bold',
      '\tfilename = magenta',
      MARK_END,
    ];
    return [{ name: 'gitconfig.fragment', content: lines.join('\n') + '\n' }];
  },

  install(p, files, { write, outDir }) {
    write(files[0]);
    return { notes: [`fragment staged at ${outDir}`] };
  },

  activate(p, files) {
    const block = files[0].content.trimEnd();
    let body = fs.existsSync(GITCONFIG) ? fs.readFileSync(GITCONFIG, 'utf8') : '';
    const re = new RegExp(`${MARK_START}[\\s\\S]*?${MARK_END}`, 'm');
    body = re.test(body) ? body.replace(re, block) : (body.trimEnd() + '\n\n' + block + '\n');
    fs.writeFileSync(GITCONFIG, body);
    return 'merged colors into ~/.gitconfig';
  },
  targets: () => [GITCONFIG],
};
