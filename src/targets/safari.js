'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { parseHex } = require('../color');
const png = require('../png');

const SRC = path.join(__dirname, '..', '..', 'extensions', 'safari');

/** Rounded-square icon with the palette's accent ramp. */
function icon(p, size) {
  const c = p.colors;
  const bg = parseHex(c.bgDarker);
  const ramp = ['cyan', 'green', 'yellow', 'orange', 'pink', 'purple'].map((k) => parseHex(c[k]));
  const r = size * 0.22;
  const inside = (x, y) => {
    const dx = Math.min(x, size - 1 - x);
    const dy = Math.min(y, size - 1 - y);
    if (dx >= r || dy >= r) return true;
    return (r - dx) ** 2 + (r - dy) ** 2 <= r * r;
  };
  return png.encode(size, size, (x, y) => {
    if (!inside(x, y)) return [0, 0, 0, 0];
    const pad = size * 0.2;
    const inner = size - pad * 2;
    if (x >= pad && x < size - pad && y >= pad && y < size - pad) {
      const band = Math.min(ramp.length - 1, Math.floor(((y - pad) / inner) * ramp.length));
      const col = ramp[band];
      return [col.r, col.g, col.b, 255];
    }
    return [bg.r, bg.g, bg.b, 255];
  });
}

module.exports = {
  id: 'safari',
  label: 'Safari / browser web extension (recolours websites)',
  detect: () => fs.existsSync('/Applications/Safari.app'),

  build(p) {
    const c = p.colors;
    const vars = Object.entries({
      bg: c.bg, 'bg-dark': c.bgDark, 'bg-darker': c.bgDarker,
      'bg-light': c.bgLight, 'bg-lighter': c.bgLighter,
      fg: c.fg, comment: c.comment, selection: c.selection, 'current-line': c.currentLine,
      cyan: c.cyan, green: c.green, orange: c.orange,
      pink: c.pink, purple: c.purple, red: c.red, yellow: c.yellow,
    }).map(([k, v]) => `  --hues-${k}: ${v};`).join('\n');

    const paletteCss = `/* ${p.name} -- generated by Hues. Do not edit by hand. */\n:root {\n${vars}\n}\n`;

    const files = [{ name: 'styles/palette.css', content: paletteCss }];

    // Copy the hand-written shell verbatim.
    for (const rel of ['manifest.json', 'content.js', 'background.js', 'popup.html', 'popup.js',
                       'styles/base.css', 'styles/sites.css']) {
      files.push({ name: rel, content: fs.readFileSync(path.join(SRC, rel)) });
    }

    // Name the extension after the palette.
    const mf = JSON.parse(fs.readFileSync(path.join(SRC, 'manifest.json'), 'utf8'));
    mf.name = `Hues — ${p.name}`;
    files[1] = { name: 'manifest.json', content: JSON.stringify(mf, null, 2) + '\n' };

    for (const size of [128, 256, 512]) {
      files.push({ name: `icons/icon-${size}.png`, content: icon(p, size) });
    }
    return files;
  },

  install(p, files, { write, outDir }) {
    files.forEach((f) => write(f));
    return {
      manual: true,
      notes: [
        `web extension built at ${outDir}`,
        'Brave/Chrome: brave://extensions -> Developer mode -> Load unpacked -> that folder',
        `Safari: xcrun safari-web-extension-converter "${outDir}" --macos-only --no-prompt`,
        'then build in Xcode and tick Safari -> Settings -> Extensions',
      ],
    };
  },
};
