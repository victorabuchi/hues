'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { parseHex } = require('../color');
const { ansi16 } = require('../ansi');

const VIM_DIR = path.join(os.homedir(), '.vim');
const VIMRC = path.join(os.homedir(), '.vimrc');
const MARK_START = '" >>> varjo >>>';
const MARK_END = '" <<< varjo <<<';

/** Nearest xterm-256 index, so the scheme still works without truecolor. */
function cterm(hex) {
  const { r, g, b } = parseHex(hex);
  const levels = [0, 95, 135, 175, 215, 255];
  const near = (v) => levels.reduce((a, l) => (Math.abs(l - v) < Math.abs(a - v) ? l : a), 0);
  const [R, G, B] = [near(r), near(g), near(b)];
  if (R === G && G === B) {
    const grey = Math.round((r + g + b) / 3);
    if (grey < 8) return 16;
    if (grey > 248) return 231;
    return 232 + Math.round(((grey - 8) / 247) * 23);
  }
  return 16 + 36 * levels.indexOf(R) + 6 * levels.indexOf(G) + levels.indexOf(B);
}

